// Every TODO(jorge) in content/, by file and line.
//
//   pnpm todos                 writes TODO-REPORT.md (git-ignored; local only)
//   node scripts/todo-report.mjs --gate
//                              runs before `next build` (pnpm build). It fails,
//                              listing every TODO left, on a Vercel production
//                              deploy (VERCEL_ENV=production) or with
//                              STRICT_TODOS=1, so the visible TODO marks never
//                              ship. A local build or a preview deploy only
//                              prints how many are left.
//                              Drafts (`draft: true`): their TODOs count only
//                              where drafts are built (not on a production
//                              deploy, src/content/drafts.ts). With
//                              STRICT_DRAFTS=1 the gate fails while any draft
//                              exists.
//
// Options for tests: --root <dir> (default: the repo), --out <file>.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import { draftsBuilt, draftsFailBuild, isDraftSource } from "../src/content/drafts.ts";
import { findTodos } from "../src/content/todos.ts";

const { values: args } = parseArgs({
  options: {
    gate: { type: "boolean", default: false },
    root: { type: "string", default: path.resolve(import.meta.dirname, "..") },
    out: { type: "string" },
  },
});

const root = path.resolve(args.root);
const drafts = draftPosts(path.join(root, "content/blog"));
// A draft that is not built leaves no TODO on the site.
const skip = draftsBuilt(process.env) ? new Set() : new Set(drafts);
const todos = collect(path.join(root, "content")).filter((t) => !skip.has(t.file));

if (args.gate) {
  if (drafts.length > 0 && draftsFailBuild(process.env)) {
    console.error(`STRICT_DRAFTS=1: the build fails while any draft is left. ${drafts.length} in content/blog:`);
    for (const file of drafts) console.error(`  ${file}`);
    process.exit(1);
  }
  if (drafts.length > 0) {
    console.log(
      draftsBuilt(process.env)
        ? `${drafts.length} draft(s), rendered at their URLs and listed nowhere: ${drafts.join(", ")}`
        : `${drafts.length} draft(s) left out of this production build: ${drafts.join(", ")}`,
    );
  }
  const strict = strictReason(process.env);
  if (todos.length > 0 && strict) {
    console.error(`${strict}: the build fails while any TODO(jorge) is left. ${todos.length} left in content/:`);
    for (const t of todos) console.error(`  ${t.file}:${t.line}  ${t.text}`);
    process.exit(1);
  }
  if (todos.length > 0) {
    console.log(
      `${todos.length} TODO(jorge) left in content/ (pnpm todos lists them; a production deploy or STRICT_TODOS=1 fails the build).`,
    );
  }
} else {
  const out = path.resolve(args.out ?? path.join(root, "TODO-REPORT.md"));
  writeFileSync(out, report(todos));
  console.log(`${todos.length} TODO(jorge) → ${path.relative(process.cwd(), out)}`);
}

/** Why this build must have no TODO left, or null when it may keep them (local, preview). */
function strictReason(env) {
  if (env.VERCEL_ENV === "production") return "Production deploy (VERCEL_ENV=production)";
  if (env.STRICT_TODOS === "1") return "STRICT_TODOS=1";
  return null;
}

/** The posts with `draft: true`, as paths from the root. */
function draftPosts(dir) {
  let names = [];
  try {
    names = readdirSync(dir).filter((f) => /\.mdx?$/.test(f));
  } catch {
    return [];
  }
  return names
    .sort()
    .map((f) => path.join(dir, f))
    .filter((file) => isDraftSource(readFileSync(file, "utf8")))
    .map((file) => path.relative(root, file));
}

/** @returns {{ file: string, line: number, text: string }[]} */
function collect(dir) {
  const files = readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && /\.(md|mdx|ts|tsx|json|ya?ml)$/.test(entry.name))
    .map((entry) => path.join(entry.parentPath, entry.name))
    .sort();
  return files.flatMap((file) =>
    readFileSync(file, "utf8")
      .split("\n")
      .flatMap((line, i) =>
        findTodos(line).map((text) => ({ file: path.relative(root, file), line: i + 1, text })),
      ),
  );
}

function report(todos) {
  const lines = [
    "# TODO report",
    "",
    "Facts missing from the content, written as `TODO(jorge): …`. Generated by `pnpm todos`; do not edit.",
    "",
  ];
  if (todos.length === 0) return [...lines, "None left.", ""].join("\n");
  return [
    ...lines,
    "| File | Line | Text |",
    "| --- | --- | --- |",
    ...todos.map((t) => `| ${t.file} | ${t.line} | ${t.text.replaceAll("|", "\\|")} |`),
    "",
  ].join("\n");
}
